"""BCC Kie.ai approval and spending integration — synthetic tests ONLY.

No live provider or credential calls. This module models approval -> reservation
-> strict receipt -> settlement without allowing any paid API request.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path
from typing import Any, Callable

from tools.bcc_claude_budget import BudgetLedger, quoted_micro_usd
from tools.bcc_kie_protocol import ProtocolBlocked, build_payload, parse_response

LIVE_EXECUTION_ENABLED = False
INPUT_OVERHEAD_ALLOWANCE_TOKENS = 4096


@dataclass(frozen=True)
class CallPlan:
    request_id: str
    input_cap: int
    output_cap: int
    held_micro_usd: int


def plan_call(task: str, *, output_cap: int = 4000) -> CallPlan:
    """Bound the dry-run estimate by UTF-8 bytes + protocol overhead.

    This is not an authoritative provider tokenizer or spending guarantee.
    No prompt caching, streaming, tool calls or external URLs are enabled.
    """
    payload = build_payload(task, max_tokens=output_cap)
    input_cap = len(task.encode("utf-8")) + INPUT_OVERHEAD_ALLOWANCE_TOKENS
    # Digest ties request ID to the exact sanitized payload, not a free-form
    # approval flag generated by a model.
    canonical = repr((payload["model"], payload["max_tokens"], task)).encode("utf-8")
    request_id = sha256(canonical).hexdigest()
    return CallPlan(request_id, input_cap, output_cap,
                    quoted_micro_usd(input_cap, output_cap))


def simulate_authorized_call(
    task: str,
    *,
    approval_id: str,
    verifier: Callable[[str, str, int], bool] | None,
    ledger_path: str | Path,
    fake_response: dict[str, Any],
    output_cap: int = 4000,
) -> dict[str, Any]:
    """Offline test-only transaction using a fake provider response.

    No credential reader is invoked. A trusted approval verifier is mandatory.
    Any unknown receipt retains its reservation; no automatic retry.
    """
    plan = plan_call(task, output_cap=output_cap)
    ledger = BudgetLedger(ledger_path, approval_verifier=verifier)
    ledger.reserve(plan.request_id, approval_id=approval_id,
                   max_input_tokens=plan.input_cap,
                   max_output_tokens=plan.output_cap)
    parsed = parse_response(fake_response, max_output_tokens=plan.output_cap)
    if parsed.usage.input_tokens > plan.input_cap:
        raise ProtocolBlocked("Provider input usage exceeds reserved cap")
    if parsed.usage.estimated_micro_usd > plan.held_micro_usd:
        raise ProtocolBlocked("Provider usage exceeds reserved amount")
    # This settlement is acceptable ONLY for a fake fixture. Production
    # requires a separately verified provider billing receipt.
    ledger.settle(plan.request_id, parsed.usage.estimated_micro_usd)
    return {"mode": "OFFLINE_MOCK_ONLY", "request_sha256": plan.request_id,
            "estimated_micro_usd": parsed.usage.estimated_micro_usd,
            "network_enabled": False, "paid_calls": "DISABLED"}


def run_paid_call(*_args: Any, **_kwargs: Any) -> None:
    raise ProtocolBlocked("Live call blocked pending trusted approval and provider billing gate")
